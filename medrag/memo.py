"""Memo export: Markdown first, then PDF.

A Streamlit app someone has to spin up is a demo format. A PDF that lands in an
inbox is a work format, and it is the thing that gets forwarded into a partner
meeting.

Two invariants:
  - fixed section order, matching the question set file order, so a reader who
    has seen one memo knows where to look in the next one
  - every claim carries a PMID or NCT and the passage it came from, so an
    analyst can verify without re-running anything
"""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from .biomarker_gating import MARKER_LABELS
from .context import TRIAL_LABEL
from .crypto import harden_outputs, write_secure
from .diligence import MemoResult, SectionResult
from .table_render import markdown_table, pdf_table

DISCLAIMER = (
    "Generated by MedRAG from public sources: PubMed and the ClinicalTrials.gov "
    "registry. Every claim is traceable to a cited passage. This is a research "
    "aid, not investment advice and not medical advice, and citations should be "
    "checked against the original source before they inform a decision."
)


def _fmt_date(stamp: datetime | None) -> str:
    return (stamp or datetime.now()).strftime("%d %B %Y")


def _fda_caveat(prov: dict) -> str | None:
    """One line stating the 510(k) sample against the total, plus the caveat that
    applicant names over-count companies. Without the sample line a memo implies a
    25-clearance sample is the whole category; without the caveat a reader counts
    four names for Imed/Alaris/CareFusion/BD and reads one product line as four
    competitors."""
    n = prov.get("n_fda", 0)
    if not n:
        return None
    store_total = prov.get("n_fda_store_total") or n
    code = prov.get("fda_product_code") or "this category"
    line = f"FDA 510(k) clearances: showing {n} of {store_total} held locally for product code {code}."
    category = prov.get("n_fda_category_total")
    if category and category > store_total:
        line += f" openFDA reports {category} cleared in this category."
    line += (" Distinct applicant names over-count distinct companies — acquisitions "
             "and renames (e.g. Imed → Alaris → CareFusion → BD are one product "
             "line) are not resolved, so a consolidated market can read as more "
             "fragmented than it is.")
    return line


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.0f}%" if d else "n/a"


def _aggregate_md(agg: dict | None) -> list[str]:
    """A landscape census, rendered as tables. Every count is over the full match
    set (SQL COUNT); the listed trials are explicitly a sample of the total, and
    NOT_MENTIONED biomarker gating is shown as a gap, never as eligibility."""
    if agg is None:
        return ["_No trial store available — this landscape census could not be computed. "
                "Run `medrag trials` for this indication first._", ""]

    total, readable = agg["total"], agg["eligibility_readable"]
    filt = agg["filters"]
    scope = filt["condition"] or "the indication"
    bm = ", ".join(f"{m} {st}" for m, st in filt["biomarker"]) if filt["biomarker"] else ""
    stat = ", ".join(filt["statuses"]) if filt["statuses"] else "all statuses"

    noun = "trial" if total == 1 else "trials"
    verb = "matches" if total == 1 else "match"
    out = [
        f"**{total} {noun}** {verb} {scope}"
        + (f", gated to {bm}" if bm else "")
        + f" ({stat}). Every count below is computed over all {total} matching records "
          "in the store, not the sample listed at the end.",
        "",
        f"Eligibility text was present and screenable on {readable} of {total} "
        f"({_pct(readable, total)}). The rest are still counted; their biomarker gating "
        "is recorded as NOT_MENTIONED, never assumed eligible.",
        "",
    ]
    if total == 0:
        out.append("_No matching trials in the store. Ingest more with `medrag trials`._")
        out.append("")
        return out

    for title, data in (("phase", agg["by_phase"]), ("status", agg["by_status"]),
                        ("sponsor class", agg["by_sponsor_class"]),
                        ("expected primary completion year", agg["by_completion_year"])):
        out.append(f"**By {title}**")
        out.append("")
        out.extend(markdown_table([title.title(), "Trials"],
                                  [[str(k), str(v)] for k, v in data.items()]))
        out.append("")

    out.append("**Biomarker gating across the field** "
               "(deterministic regex census — NOT_MENTIONED is a gap in the registry text, "
               "not a statement of eligibility)")
    out.append("")
    out.extend(markdown_table(
        ["Marker", "Required", "Excluded", "Not mentioned"],
        [[MARKER_LABELS.get(mk, mk), str(c["REQUIRED"]), str(c["EXCLUDED"]), str(c["NOT_MENTIONED"])]
         for mk, c in agg["by_biomarker"].items()]))
    out.append("")

    shown, dropped = agg["shown"], agg["dropped"]
    out.append(f"**Trials — showing {shown} of {total}**")
    out.append("")
    if dropped:
        out.append(f"> {dropped} matching trial(s) are NOT listed below: this is a sample "
                   f"capped at {shown}. The counts above cover all {total}.")
        out.append("")
    rows = []
    for rec, flags in zip(agg["sample"], agg["sample_flags"]):
        gated = ", ".join(
            f"{MARKER_LABELS.get(m, m)}:{f['status']}"
            for m, f in (flags or {}).items() if f.get("status") != "NOT_MENTIONED"
        ) or "—"
        rows.append([f"`{rec.nct_id}`", rec.brief_title or "(untitled)",
                     rec.phase or "—", rec.overall_status or "—",
                     rec.lead_sponsor or "—", gated])
    out.extend(markdown_table(["NCT", "Title", "Phase", "Status", "Sponsor", "Gating"], rows))
    out.append("")
    return out


def _section_md(s: SectionResult) -> list[str]:
    out = [f"## {s.question.section}", ""]
    out.append(f"*{s.rendered_question}*")
    out.append("")
    if s.aggregate is not None:
        out.extend(_aggregate_md(s.aggregate))
    else:
        out.append(s.answer.text)
        out.append("")

    if s.negative is not None:
        out.append("### Contradicting or unsupportive evidence")
        out.append("")
        if s.negative.stopped_trials:
            out.append("**Trials stopped early**")
            out.append("")
            for st in s.negative.stopped_trials:
                r = st.record
                bits = [f"`{r.nct_id}`", r.overall_status]
                if r.phase:
                    bits.append(r.phase)
                if r.enrollment_count is not None:
                    bits.append(f"n={r.enrollment_count}")
                if r.lead_sponsor:
                    bits.append(r.lead_sponsor)
                out.append(f"- {' · '.join(bits)} — **{st.reason}**")
            out.append("")
        # FDA recalls and adverse events are database facts like the stopped
        # trials, but a recall and a halted trial are different failure modes, so
        # they get their own headings rather than one merged "bad things" list.
        if s.negative.recalls:
            out.append("**FDA recalls**")
            out.append("")
            for r in s.negative.recalls:
                bits = [f"`{r.recall_number}`", r.recall_status or "status not stated"]
                if r.root_cause_description:
                    bits.append(r.root_cause_description)
                if r.recalling_firm:
                    bits.append(r.recalling_firm)
                reason = (r.reason_for_recall or "no reason stated").strip()
                out.append(f"- {' · '.join(bits)} — {reason}")
            out.append("")
        if s.negative.adverse_events:
            total = s.negative.events_shown_of
            out.append(f"**FDA adverse events** (showing {len(s.negative.adverse_events)} "
                       f"of {total} on file, most severe first)")
            out.append("")
            for e in s.negative.adverse_events:
                head = f"`{e.report_number}` · **{e.event_type or 'unspecified'}**"
                if e.brand_name:
                    head += f" · {e.brand_name}"
                problems = ", ".join(e.product_problems[:2]) if e.product_problems else ""
                if problems:
                    head += f" · {problems}"
                out.append(f"- {head}")
            out.append("")
        if s.negative.findings:
            out.append("**Findings against**")
            out.append("")
            for f in s.negative.findings:
                tag = f" *[{f.grade_tag}]*" if f.grade_tag else ""
                out.append(f"- ({f.kind}) {f.point} [{f.citation}]{tag}")
            out.append("")
        if s.negative.is_empty or not s.negative.searched:
            out.append(f"{s.negative.summary()}")
            out.append("")
        if s.negative.note:
            out.append(f"> {s.negative.note}")
            out.append("")

    fda_caveat = _fda_caveat(s.provenance)
    if fda_caveat:
        out.append(f"> {fda_caveat}")
        out.append("")

    if s.evidence:
        out.append("<details><summary>Sources for this section</summary>")
        out.append("")
        for e in s.evidence:
            out.append(f"- {e.bib_line()}")
        out.append("")
        out.append("</details>")
        out.append("")

    prov = s.provenance
    meta = [
        f"route: {s.route.value} ({s.route_method})",
        f"trial records: {prov.get('n_trials', 0)}",
        f"literature: {prov.get('n_literature', 0)}",
        f"validation: {s.validation.summary()}",
    ]
    out.append(f"<sub>{' · '.join(meta)}</sub>")
    out.append("")
    return out


def _memo_title(memo: MemoResult) -> str:
    """Asset-anchored memos title on the asset; an indication-only landscape run
    titles on the indication so the header is not a bare dash."""
    if memo.asset:
        return f"Diligence memo — {memo.asset}"
    return f"Landscape — {memo.indication or 'not specified'}"


def render_markdown(memo: MemoResult, generated: datetime | None = None) -> str:
    cov = memo.coverage()
    lines = [
        f"# {_memo_title(memo)}",
        "",
        f"**Asset:** {memo.asset or 'none (indication-first landscape)'}  ",
        f"**Indication:** {memo.indication or 'not specified'}  ",
        f"**Question set:** {memo.question_set}  ",
        f"**Generated:** {_fmt_date(generated)}  ",
        f"**Model:** {memo.model} · **Embeddings:** {memo.embedder}",
        "",
        "---",
        "",
        "## Coverage",
        "",
        f"- Sections answered with evidence: {cov['sections_with_evidence']}/{cov['sections']}",
        f"- Sections checked for faithfulness: {cov['sections_assessed']}/{cov['sections']}",
        f"- Of those checked, passing: {cov['sections_passing_validation']}/{cov['sections_assessed']}"
        if cov["sections_assessed"] else "- Of those checked, passing: n/a — none were checked",
        f"- Trials found stopped early: {cov['stopped_trials_found']}",
        f"- Contradicting or undercutting findings: {cov['contradicting_findings']}",
        "",
    ]

    if memo.warnings:
        lines.append("**Warnings**")
        lines.append("")
        # Surfaced at the top, not buried: a memo built without the trial store
        # looks complete and is not.
        for w in memo.warnings:
            lines.append(f"- {w}")
        lines.append("")

    lines.append("---")
    lines.append("")

    for s in memo.sections:
        lines.extend(_section_md(s))
        lines.append("---")
        lines.append("")

    lines.append("## Full source list")
    lines.append("")
    seen: set[str] = set()
    for e in memo.all_evidence:
        if e.identifier in seen:
            continue
        seen.add(e.identifier)
        kind = "trial" if e.kind == TRIAL_LABEL else "paper"
        tag = f" [{e.grade_tag}]" if e.grade_tag else ""
        title = e.title or "(untitled)"
        url = f" — {e.url}" if e.url else ""
        lines.append(f"- `{e.identifier}` ({kind}){tag} {title}{url}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append(f"*{DISCLAIMER}*")
    lines.append("")

    return "\n".join(lines)


