_MD_INLINE = re.compile(r"\*\*(.+?)\*\*|\*(.+?)\*|`(.+?)`")


def _inline_to_rl(text: str) -> str:
    """Convert the small Markdown subset used above into ReportLab markup.

    Escaping happens first: an unescaped ampersand or angle bracket in a paper
    title will otherwise abort the whole PDF build.
    """
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<!\*)\*([^*]+?)\*(?!\*)", r"<i>\1</i>", text)
    text = re.sub(r"`(.+?)`", r"<font face='Courier'>\1</font>", text)
    return text


def _aggregate_pdf(agg, story, styles, Paragraph, Spacer, inch) -> None:
    """PDF rendering of a landscape census: denominator, biomarker census table,
    and a sample table labelled against the total."""
    if agg is None:
        story.append(Paragraph("No trial store available — census not computed.", styles["body"]))
        return
    total, readable = agg["total"], agg["eligibility_readable"]
    filt = agg["filters"]
    bm = ", ".join(f"{m} {st}" for m, st in filt["biomarker"]) if filt["biomarker"] else ""
    stat = ", ".join(filt["statuses"]) if filt["statuses"] else "all statuses"
    story.append(Paragraph(_inline_to_rl(
        f"<b>{total} trials</b> match {filt['condition'] or 'the indication'}"
        + (f", gated to {bm}" if bm else "") + f" ({stat}). Counts are over all {total}, "
        "not the sample below."), styles["body"]))
    if total == 0:
        return
    story.append(Paragraph(_inline_to_rl(
        f"Eligibility text screenable on {readable}/{total} ({_pct(readable, total)}); "
        "the rest are counted with NOT_MENTIONED gating, never assumed eligible."), styles["small"]))
    for title, data in (("Phase", agg["by_phase"]), ("Status", agg["by_status"]),
                        ("Sponsor class", agg["by_sponsor_class"]),
                        ("Primary completion year", agg["by_completion_year"])):
        summary = ", ".join(f"{k}: {v}" for k, v in data.items())
        story.append(Paragraph(_inline_to_rl(f"<b>{title}</b> — {summary}"), styles["small"]))

    story.append(Paragraph("Biomarker gating (NOT_MENTIONED is a gap, not eligibility)", styles["h3"]))
    rows = [[MARKER_LABELS.get(mk, mk), str(c["REQUIRED"]), str(c["EXCLUDED"]), str(c["NOT_MENTIONED"])]
            for mk, c in agg["by_biomarker"].items()]
    story.append(pdf_table(["Marker", "Required", "Excluded", "Not mentioned"],
                           [[_inline_to_rl(str(x)) for x in r] for r in rows],
                           [1.9 * inch, 1.1 * inch, 1.1 * inch, 1.3 * inch], styles["small"]))
    story.append(Spacer(1, 8))

    shown, dropped = agg["shown"], agg["dropped"]
    story.append(Paragraph(f"Trials — showing {shown} of {total}", styles["h3"]))
    if dropped:
        story.append(Paragraph(_inline_to_rl(
            f"{dropped} matching trial(s) not listed: this is a sample capped at {shown}. "
            f"The counts above cover all {total}."), styles["note"]))
    srows = []
    for rec, flags in zip(agg["sample"], agg["sample_flags"]):
        gated = ", ".join(f"{MARKER_LABELS.get(m, m)}:{f['status']}"
                          for m, f in (flags or {}).items() if f.get("status") != "NOT_MENTIONED") or "—"
        srows.append([_inline_to_rl(rec.nct_id), _inline_to_rl(rec.brief_title or "(untitled)"),
                      _inline_to_rl(rec.phase or "—"), _inline_to_rl(rec.overall_status or "—"),
                      _inline_to_rl(rec.lead_sponsor or "—"), _inline_to_rl(gated)])
    story.append(pdf_table(["NCT", "Title", "Phase", "Status", "Sponsor", "Gating"], srows,
                           [0.9 * inch, 2.0 * inch, 0.6 * inch, 1.0 * inch, 1.3 * inch, 1.4 * inch],
                           styles["small"]))
    story.append(Spacer(1, 8))


def render_pdf(memo: MemoResult, path: str | Path, generated: datetime | None = None) -> Path:
    """Build the PDF directly from the memo object.

    Deliberately not a Markdown-to-PDF conversion: rendering from the structured
    result keeps the section order and the citation data authoritative in one
    place, so the two formats cannot drift.
    """
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import LETTER
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import (
        HRFlowable,
        ListFlowable,
        ListItem,
        PageBreak,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
    )

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle("t", parent=base["Title"], fontSize=20, spaceAfter=6),
        "sub": ParagraphStyle("s", parent=base["Normal"], fontSize=9,
                              textColor="#555555", spaceAfter=2),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], fontSize=13,
                             spaceBefore=14, spaceAfter=6),
        "h3": ParagraphStyle("h3", parent=base["Heading3"], fontSize=11,
                             spaceBefore=10, spaceAfter=4, textColor="#8B0000"),
        "body": ParagraphStyle("b", parent=base["Normal"], fontSize=10, leading=14,
                               alignment=TA_LEFT, spaceAfter=6),
        "q": ParagraphStyle("q", parent=base["Normal"], fontSize=10, leading=13,
                            textColor="#333333", leftIndent=10, spaceAfter=8,
                            fontName="Helvetica-Oblique"),
        "small": ParagraphStyle("sm", parent=base["Normal"], fontSize=8, leading=11,
                                textColor="#666666", spaceAfter=4),
        "note": ParagraphStyle("n", parent=base["Normal"], fontSize=9, leading=12,
                               leftIndent=12, textColor="#444444",
                               borderPadding=4, spaceAfter=8),
    }

    story = []
    cov = memo.coverage()

    story.append(Paragraph(_inline_to_rl(_memo_title(memo)), styles["title"]))
    for line in (
        f"Indication: {memo.indication or 'not specified'}",
        f"Question set: {memo.question_set}",
        f"Generated: {_fmt_date(generated)}",
        f"Model: {memo.model} · Embeddings: {memo.embedder}",
    ):
        story.append(Paragraph(_inline_to_rl(line), styles["sub"]))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", color="#cccccc"))

    story.append(Paragraph("Coverage", styles["h2"]))
    story.append(
        ListFlowable(
            [
                ListItem(Paragraph(t, styles["body"]))
                for t in (
                    f"Sections answered with evidence: {cov['sections_with_evidence']}/{cov['sections']}",
                    f"Sections checked for faithfulness: {cov['sections_assessed']}/{cov['sections']}",
                    (f"Of those checked, passing: {cov['sections_passing_validation']}/{cov['sections_assessed']}"
                     if cov["sections_assessed"] else "Of those checked, passing: n/a — none were checked"),
                    f"Trials found stopped early: {cov['stopped_trials_found']}",
                    f"Contradicting or undercutting findings: {cov['contradicting_findings']}",
                )
            ],
            bulletType="bullet",
            leftIndent=16,
        )
    )

    if memo.warnings:
        story.append(Paragraph("Warnings", styles["h3"]))
        for w in memo.warnings:
            story.append(Paragraph(_inline_to_rl(w), styles["body"]))


    for s in memo.sections:
        story.append(Paragraph(_inline_to_rl(s.question.section), styles["h2"]))
        story.append(Paragraph(_inline_to_rl(s.rendered_question), styles["q"]))

        if s.aggregate is not None:
            _aggregate_pdf(s.aggregate, story, styles, Paragraph, Spacer, inch)
        else:
            for para in s.answer.text.split("\n"):
                if para.strip():
                    story.append(Paragraph(_inline_to_rl(para.strip()), styles["body"]))

        if s.negative is not None:
            story.append(Paragraph("Contradicting or unsupportive evidence", styles["h3"]))
            if s.negative.stopped_trials:
                items = []
                for st in s.negative.stopped_trials:
                    r = st.record
                    head = f"<b>{r.nct_id}</b> — {r.overall_status}"
                    if r.phase:
                        head += f", {r.phase}"
                    if r.lead_sponsor:
                        head += f" ({_inline_to_rl(r.lead_sponsor)})"
                    items.append(
                        ListItem(Paragraph(f"{head}<br/>Reason: {_inline_to_rl(st.reason)}",
                                           styles["body"]))
                    )
                story.append(ListFlowable(items, bulletType="bullet", leftIndent=16))
            if s.negative.recalls:
                story.append(Paragraph("FDA recalls", styles["small"]))
                story.append(ListFlowable(
                    [ListItem(Paragraph(
                        f"<b>{_inline_to_rl(r.recall_number)}</b> — "
                        f"{_inline_to_rl(r.recall_status or 'status not stated')}"
                        + (f" ({_inline_to_rl(r.root_cause_description)})"
                           if r.root_cause_description else "")
                        + f"<br/>{_inline_to_rl((r.reason_for_recall or 'no reason stated').strip())}",
                        styles["body"])) for r in s.negative.recalls],
                    bulletType="bullet", leftIndent=16))
            if s.negative.adverse_events:
                story.append(Paragraph(
                    f"FDA adverse events (showing {len(s.negative.adverse_events)} of "
                    f"{s.negative.events_shown_of} on file, most severe first)", styles["small"]))
                story.append(ListFlowable(
                    [ListItem(Paragraph(
                        f"<b>{_inline_to_rl(e.report_number)}</b> — <b>{e.event_type or 'unspecified'}</b>"
                        + (f" · {_inline_to_rl(e.brand_name)}" if e.brand_name else "")
                        + (f" · {_inline_to_rl(', '.join(e.product_problems[:2]))}"
                           if e.product_problems else ""),
                        styles["body"])) for e in s.negative.adverse_events],
                    bulletType="bullet", leftIndent=16))
            if s.negative.findings:
                story.append(
                    ListFlowable(
                        [
                            ListItem(
                                Paragraph(
                                    f"({f.kind}) {_inline_to_rl(f.point)} "
                                    f"[{f.citation}]"
                                    + (f" <i>[{f.grade_tag}]</i>" if f.grade_tag else ""),
                                    styles["body"],
                                )
                            )
                            for f in s.negative.findings
                        ],
                        bulletType="bullet",
                        leftIndent=16,
                    )
                )
            if s.negative.is_empty or not s.negative.searched:
                story.append(Paragraph(_inline_to_rl(s.negative.summary()), styles["note"]))
            if s.negative.note:
                story.append(Paragraph(_inline_to_rl(s.negative.note), styles["note"]))

        fda_caveat = _fda_caveat(s.provenance)
        if fda_caveat:
            story.append(Paragraph(_inline_to_rl(fda_caveat), styles["note"]))

        if s.evidence:
            story.append(Paragraph("Sources for this section", styles["h3"]))
            for e in s.evidence:
                story.append(Paragraph(_inline_to_rl(e.bib_line()), styles["small"]))

        prov = s.provenance
        story.append(
            Paragraph(
                f"route: {s.route.value} ({s.route_method}) · "
                f"trial records: {prov.get('n_trials', 0)} · "
                f"literature: {prov.get('n_literature', 0)} · "
                f"validation: {_inline_to_rl(s.validation.summary())}",
                styles["small"],
            )
        )
        story.append(HRFlowable(width="100%", color="#dddddd"))

    story.append(PageBreak())
    story.append(Paragraph("Full source list", styles["h2"]))
    seen: set[str] = set()
    for e in memo.all_evidence:
        if e.identifier in seen:
            continue
        seen.add(e.identifier)
        kind = "trial" if e.kind == TRIAL_LABEL else "paper"
        tag = f" [{e.grade_tag}]" if e.grade_tag else ""
        story.append(
            Paragraph(
                f"<font face='Courier'>{_inline_to_rl(e.identifier)}</font> ({kind}){tag} "
                f"{_inline_to_rl(e.title or '(untitled)')}"
                + (f"<br/><font size=7>{_inline_to_rl(e.url)}</font>" if e.url else ""),
                styles["small"],
            )
        )

    story.append(Spacer(1, 14))
    story.append(Paragraph(_inline_to_rl(DISCLAIMER), styles["small"]))

    SimpleDocTemplate(
        str(path),
        pagesize=LETTER,
        leftMargin=0.9 * inch,
        rightMargin=0.9 * inch,
        topMargin=0.9 * inch,
        bottomMargin=0.9 * inch,
        title=_memo_title(memo),
        author="MedRAG",
    ).build(story)

    return path


def export(
    memo: MemoResult,
    out_dir: str | Path,
    stem: str | None = None,
    passphrase: str | None = None,
) -> dict[str, Path]:
    """Write both formats and return their paths.

    The two formats get different treatment on purpose. The Markdown is the
    machine-readable copy that sits in `out/` between sessions, so it goes
    through `write_secure` and is encrypted whenever a passphrase is configured —
    the same protection the corpus has always had. The PDF is the artifact people
    circulate; encrypting it would produce a file no reader can open, so it stays
    plaintext at 0600 and the boundary is documented in SECURITY.md rather than
    pretended away.

    Passing no passphrase while MEDRAG_ENCRYPT is set raises from `write_secure`
    rather than silently writing cleartext. That is the existing fail-closed
    guard and it is deliberate: a memo that quietly loses its encryption is worse
    than a run that stops and says so.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = stem or re.sub(r"[^a-z0-9]+", "-", (memo.asset or memo.indication).lower()).strip("-") or "memo"

    md_path = out_dir / f"{stem}-diligence.md"
    write_secure(md_path, render_markdown(memo).encode("utf-8"), passphrase)
    pdf_path = render_pdf(memo, out_dir / f"{stem}-diligence.pdf")
    harden_outputs(out_dir, md_path, pdf_path)
    return {"markdown": md_path, "pdf": pdf_path}
